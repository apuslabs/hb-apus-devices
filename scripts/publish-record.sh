#!/usr/bin/env bash
# Render the publication record (PUBLISH.md) from the output of
# `rebar3 device publish`. Called by `make publish`.
#
# Usage: scripts/publish-record.sh PUBLISH_LOG HYPERBEAM_REF > PUBLISH.md
#
# The record lists the signer address, the source commit, the pinned
# HyperBEAM commit and the Device-Specification and Device-Implementation
# message IDs of every device in PUBLISH_LOG.
set -euo pipefail

usage="usage: scripts/publish-record.sh PUBLISH_LOG HYPERBEAM_REF"
log=${1:?$usage}
hyperbeam_ref=${2:?$usage}

id='[A-Za-z0-9_-]{43}'
rows=$(sed -nE \
    "s/.*Published device: ([^;]+); Specification ID: ($id); Implementation ID: ($id); Signer: ($id)\..*/\1 \2 \3 \4/p" \
    "$log")

if [ -z "$rows" ]; then
    echo "error: $log lists no published device" >&2
    exit 1
fi

signer=$(awk '{ print $4 }' <<<"$rows" | sort -u)
if [ "$(wc -l <<<"$signer")" -ne 1 ]; then
    echo "error: $log lists more than one signer" >&2
    exit 1
fi

commit=$(git rev-parse HEAD)
published_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)

cat <<EOF
# Published Device Messages

This record is generated by \`make publish\`. Each device is published as a
signed Device-Specification message and a Device-Implementation message
whose \`implements-device\` tag is the specification ID.

| Field | Value |
|---|---|
| Published at | $published_at |
| Signer | \`$signer\` |
| Source commit | \`$commit\` |
| HyperBEAM | \`apuslabs/HyperBEAM\` at \`$hyperbeam_ref\` |

| Device | Specification ID | Implementation ID |
|---|---|---|
EOF

while read -r name spec impl _; do
    printf '| `%s` | `%s` | `%s` |\n' "$name" "$spec" "$impl"
done <<<"$rows"
